package com.boutique.ecommerce.dao;

import com.boutique.ecommerce.config.DBConnection;
import com.boutique.ecommerce.model.Product;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

/**
 * ProductDAO - Data Access Object for Products
 *
 * Encapsulates all CRUD database operations for products using PreparedStatement.
 *
 * Beginner JDBC Concepts Explained:
 * - Statement.RETURN_GENERATED_KEYS: Requests the database server to return the auto-generated
 *   primary key (e.g. AUTO_INCREMENT product_id) generated by an INSERT.
 * - pstmt.getGeneratedKeys(): Retrieves the ResultSet containing generated key columns.
 * - Parameterized Queries: Replacing variables with '?' binds user input as literal values,
 *   making queries completely immune to SQL injection.
 */
public class ProductDAO {

    /**
     * Retrieves all products available in the catalog.
     *
     * @return List of all products ordered by category and product ID.
     * @throws SQLException if a database error occurs.
     */
    public List<Product> getAllProducts() throws SQLException {
        List<Product> products = new ArrayList<>();
        String sql = "SELECT product_id, name, category, price, stock_quantity, description, created_at " +
                     "FROM products ORDER BY category, product_id";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql);
             ResultSet rs = pstmt.executeQuery()) {

            while (rs.next()) {
                products.add(mapRowToProduct(rs));
            }
        } catch (SQLException e) {
            throw new SQLException("Error retrieving products: " + e.getMessage(), e);
        }
        return products;
    }

    /**
     * Finds a single product by its unique product ID.
     *
     * @param productId The ID to look up.
     * @return The Product object, or null if not found.
     * @throws SQLException if a database error occurs.
     */
    public Product getProductById(int productId) throws SQLException {
        String sql = "SELECT product_id, name, category, price, stock_quantity, description, created_at " +
                     "FROM products WHERE product_id = ?";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setInt(1, productId);

            try (ResultSet rs = pstmt.executeQuery()) {
                if (rs.next()) {
                    return mapRowToProduct(rs);
                }
            }
        } catch (SQLException e) {
            throw new SQLException("Error finding product with ID [" + productId + "]: " + e.getMessage(), e);
        }
        return null;
    }

    /**
     * Searches products where name or category contains the specified search term.
     *
     * @param keyword The search keyword.
     * @return List of matching products.
     * @throws SQLException if a database error occurs.
     */
    public List<Product> searchProducts(String keyword) throws SQLException {
        List<Product> results = new ArrayList<>();
        String sql = "SELECT product_id, name, category, price, stock_quantity, description, created_at " +
                     "FROM products WHERE LOWER(name) LIKE ? OR LOWER(category) LIKE ? ORDER BY category, name";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            String pattern = "%" + (keyword == null ? "" : keyword.toLowerCase().trim()) + "%";
            pstmt.setString(1, pattern);
            pstmt.setString(2, pattern);

            try (ResultSet rs = pstmt.executeQuery()) {
                while (rs.next()) {
                    results.add(mapRowToProduct(rs));
                }
            }
        } catch (SQLException e) {
            throw new SQLException("Error searching products with keyword [" + keyword + "]: " + e.getMessage(), e);
        }
        return results;
    }

    /**
     * Inserts a new product into the database.
     *
     * @param product The product to insert.
     * @return The product with generated product_id, or null if insertion failed.
     * @throws SQLException if a database error occurs.
     */
    public Product addProduct(Product product) throws SQLException {
        String sql = "INSERT INTO products (name, category, price, stock_quantity, description) VALUES (?, ?, ?, ?, ?)";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {

            pstmt.setString(1, product.getName());
            pstmt.setString(2, product.getCategory());
            pstmt.setDouble(3, product.getPrice());
            pstmt.setInt(4, product.getStockQuantity());
            pstmt.setString(5, product.getDescription());

            int affectedRows = pstmt.executeUpdate();
            if (affectedRows > 0) {
                try (ResultSet generatedKeys = pstmt.getGeneratedKeys()) {
                    if (generatedKeys.next()) {
                        product.setProductId(generatedKeys.getInt(1));
                    }
                }
                return product;
            }
        } catch (SQLException e) {
            throw new SQLException("Error adding product: " + e.getMessage(), e);
        }
        return null;
    }

    /**
     * Updates an existing product's details in the database.
     *
     * @param product The product object with updated values.
     * @return true if updated successfully, false otherwise.
     * @throws SQLException if a database error occurs.
     */
    public boolean updateProduct(Product product) throws SQLException {
        String sql = "UPDATE products SET name = ?, category = ?, price = ?, stock_quantity = ?, description = ? WHERE product_id = ?";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setString(1, product.getName());
            pstmt.setString(2, product.getCategory());
            pstmt.setDouble(3, product.getPrice());
            pstmt.setInt(4, product.getStockQuantity());
            pstmt.setString(5, product.getDescription());
            pstmt.setInt(6, product.getProductId());

            return pstmt.executeUpdate() > 0;
        } catch (SQLException e) {
            throw new SQLException("Error updating product ID [" + product.getProductId() + "]: " + e.getMessage(), e);
        }
    }

    /**
     * Deletes a product by its ID.
     * If the product has already been ordered, foreign key constraints prevent deletion.
     *
     * @param productId The ID of the product to delete.
     * @return true if deleted, false otherwise.
     * @throws SQLException if a database error occurs or foreign key prevents deletion.
     */
    public boolean deleteProduct(int productId) throws SQLException {
        String sql = "DELETE FROM products WHERE product_id = ?";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setInt(1, productId);
            return pstmt.executeUpdate() > 0;
        } catch (SQLException e) {
            // Check for foreign key constraint violation (SQLState 23000 / ErrorCode 1451)
            if ("23000".equals(e.getSQLState()) || e.getErrorCode() == 1451) {
                throw new SQLException("Cannot delete product: This product is linked to existing order history. " +
                        "Tip: Consider updating its stock to 0 instead of deleting.", e);
            }
            throw new SQLException("Error deleting product ID [" + productId + "]: " + e.getMessage(), e);
        }
    }

    /**
     * Helper method to map a ResultSet row to a Product object.
     */
    private Product mapRowToProduct(ResultSet rs) throws SQLException {
        return new Product(
                rs.getInt("product_id"),
                rs.getString("name"),
                rs.getString("category"),
                rs.getDouble("price"),
                rs.getInt("stock_quantity"),
                rs.getString("description"),
                rs.getTimestamp("created_at")
        );
    }
}
